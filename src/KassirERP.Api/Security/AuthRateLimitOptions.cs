namespace KassirERP.Api.Security;

/// <summary>
/// Лимит запросов на /auth/* с одного IP (секция RateLimits:Auth), token bucket.
///
/// Расчёт для магазина на 50 касс за одним NAT — все кассы приходят с одного IP:
/// - начало смены: 50 входов по PIN почти одновременно, плюс ошибки ввода
///   (до 4 на кассу до блокировки учётки) — худший всплеск ≈ 50 × 4 = 200;
/// - дальше входов почти нет: токен по PIN живёт смену (12 ч), повторный вход —
///   после перезапуска кассы или смены кассира.
/// Поэтому запас — 200 запросов (весь худший всплеск проходит без отказа),
/// пополнение — 60 в минуту (1 в секунду; за 3–4 минуты запас восстанавливается).
///
/// От перебора PIN защищает не этот лимит, а блокировка учётки (5 попыток на
/// 15 минут, auth.begin_attempt). Лимит по IP ограничивает «распыление» —
/// перебор по многим учёткам: не больше 3 600 попыток в час с одного адреса.
/// </summary>
public sealed class AuthRateLimitOptions
{
    public const string Section = "RateLimits:Auth";

    /// <summary>Сколько запросов проходит подряд (размер всплеска).</summary>
    public int TokenLimit { get; set; } = 200;

    /// <summary>Сколько запросов в минуту добавляется к запасу.</summary>
    public int TokensPerMinute { get; set; } = 60;
}
